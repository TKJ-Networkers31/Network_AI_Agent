function extractSvgInner(svgString = "") {
  if (!svgString) return "";
  const match = svgString.match(/<svg[^>]*>([\s\S]*?)<\/svg>/i);
  return match ? match[1].trim() : svgString;
}

/**
 * Creates a reusable React SVG component from a registered asset key
 */
export function createSvgComponent(key) {
  const innerHtml = extractSvgInner(DEVICE_SVG_RAW[key]);
  return function DeviceSvgIcon({ className = "w-10 h-10", style, ...props }) {
    return React.createElement("svg", {
      viewBox: "0 0 64 64",
      fill: "none",
      xmlns: "http://www.w3.org/2000/svg",
      className,
      style,
      dangerouslySetInnerHTML: { __html: innerHtml },
      ...props,
    });
  };
}

